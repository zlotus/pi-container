#!/usr/bin/env bash
# Generates the Control Plane host's secrets once (specs.md Phase 19.5). Writes only files
# that do not exist yet, prints only file names, never a secret.
#
#   init-secrets.sh
#
#   /etc/agent-runtime/postgres.env                 PostgreSQL superuser       root 0600
#   /etc/agent-runtime/control-plane.secrets.env    DATABASE_URL, SESSION_SECRET,
#                                                   MODEL_GATEWAY_MASTER_KEY,
#                                                   WORKER_GATEWAY_TOKENS_JSON  root:agent-runtime-cp 0640
#   /etc/agent-runtime/litellm.env                  LITELLM_MASTER_KEY, DATABASE_URL; add
#                                                   the upstream provider keys yourself       root 0600
#   /etc/agent-runtime/metrics.token                Prometheus scrape token    agent-runtime-cp 0600
#
# Environment: AGENT_RUNTIME_ETC (/etc/agent-runtime), AR_POSTGRES_PORT (5432, as in
# nginx.env / compose), AGENT_RUNTIME_CP_GROUP (agent-runtime-cp).
set -euo pipefail

etc="${AGENT_RUNTIME_ETC:-/etc/agent-runtime}"
group="${AGENT_RUNTIME_CP_GROUP:-agent-runtime-cp}"
port="${AR_POSTGRES_PORT:-5432}"
umask 077

[[ "$(id -u)" -eq 0 ]] || { echo "init-secrets.sh: run as root" >&2; exit 1; }
getent group "$group" >/dev/null || { echo "init-secrets.sh: group $group does not exist" >&2; exit 1; }
mkdir -p "$etc"

random() { openssl rand -hex 32; }

write_once() { # write_once <file> <mode> <owner> < content
  local file="$1" mode="$2" owner="$3"
  if [[ -e "$file" ]]; then
    echo "kept     $file (exists)"
    cat >/dev/null
    return
  fi
  install -m "$mode" -o "${owner%%:*}" -g "${owner##*:}" /dev/stdin "$file"
  echo "created  $file"
}

platform_password="$(random)"
litellm_password="$(random)"
master_key="sk-$(random)"

write_once "${etc}/postgres.env" 0600 root:root <<EOF
POSTGRES_USER=postgres
POSTGRES_PASSWORD=$(random)
EOF

write_once "${etc}/control-plane.secrets.env" 0640 "root:${group}" <<EOF
# Generated by init-secrets.sh. Keep values unquoted, one per line (systemd EnvironmentFile).
DATABASE_URL=postgres://agent_runtime:${platform_password}@127.0.0.1:${port}/agent_runtime
SESSION_SECRET=$(random)
MODEL_GATEWAY_MASTER_KEY=${master_key}
# {"<worker id>":"<WORKER_GATEWAY_TOKEN printed by agent-runtime-ctl worker:provision>"}
WORKER_GATEWAY_TOKENS_JSON={}
# AUTH_OIDC_CLIENT_SECRET=
# AUTH_OAUTH2_CLIENT_SECRET=
EOF

write_once "${etc}/litellm.env" 0600 root:root <<EOF
# Generated by init-secrets.sh. Add the upstream provider keys named in model-gateway/config.yaml:
# DEEPSEEK_API_KEY=
# XIAOMI_API_KEY=
LITELLM_MASTER_KEY=${master_key}
DATABASE_URL=postgresql://litellm:${litellm_password}@postgres:5432/litellm
EOF

# The Control Plane requires its own 0600 file (Phase 17.8); Prometheus gets a copy.
write_once "${etc}/metrics.token" 0600 "${group}:${group}" <<EOF
$(random)
EOF

echo "next: init-postgres.sh creates the agent_runtime and litellm roles with these passwords"
